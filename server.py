client = TelegramClient('varta_ukraine_session_v12', API_ID, API_HASH)

@client.on(events.NewMessage(chats=ALL_CHANNELS))
async def handle_incoming_feed(event):
    text = event.raw_text.lower()
    channel_username = getattr(event.chat, 'username', 'channel')

    if any(bad in text for bad in EXCLUDE_WORDS):
        return

    clean_text = event.raw_text.strip()
    is_outage = any(w in text for w in ['світл', 'відключ', 'графік', 'обленерго', 'укренерго'])

    target_reg = "Харківська область"
    for reg in ukraine_absolute_full_db.keys():
        reg_keyword = reg.split()[0].lower()
        if reg_keyword in text:
            target_reg = reg
            break

    if is_outage:
        live_state["outages_status"][target_reg] = f"[@{channel_username}]: {clean_text[:140]}..."
    else:
        if any(w in text for w in ['ракет', 'балістик', 'шахед', 'бпла', 'увага', 'зліт міг']):
            live_state["air_alerts"][target_reg]["code"] = "red"
            live_state["air_alerts"][target_reg]["text"] = "ТРИВОГА / ЗАГРОЗА"
            live_state["air_alerts"][target_reg]["detail"] = f"[@{channel_username}]: {clean_text[:130]}..."

            live_state["radar"].insert(0, {
                "title": f"📍 {target_reg}",
                "route": clean_text[:110] + "...",
                "tag": "ТРИВОГА"
            })
            live_state["radar"] = live_state["radar"][:10]

async def start_telegram():
    if API_ID and API_HASH:
        await client.start()

@app.on_event("startup")
async def startup_event():
    asyncio.create_task(start_telegram())

